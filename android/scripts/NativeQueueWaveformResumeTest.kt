/** Exact Queue primaryAction body (generated by test-queue-waveform-integration.py),
 * real ControllerProjection, Media3 session/service, repository and native player.
 * Only native audio hardware/acquisition are boundary facades; no mounted UI claim. */
@RunWith(RobolectricTestRunner::class)
@Config(manifest=Config.NONE,sdk=[28],application=QueueResumeApplication::class)
@androidx.annotation.OptIn(androidx.media3.common.util.UnstableApi::class)
internal class NativeQueueWaveformResumeTest {
    private class Fixture:AutoCloseable {
        val app=RuntimeEnvironment.getApplication() as QueueResumeApplication
        val lifecycle=Robolectric.buildService(SoundQLibraryService::class.java).create()
        val service=lifecycle.get()
        fun field(name:String)=service.javaClass.getDeclaredField(name).apply{isAccessible=true}
        val player=field("player").get(service) as NativeCallbackPlayer
        val hardware get()=app.hardware
        @Suppress("UNCHECKED_CAST") val grants=field("grants").get(service) as ConcurrentHashMap<String,MediaGrant>
        val session=field("session").get(service) as MediaSession
        val projection:ControllerProjection
        val queue:QueueResumeEntrypoint
        init {
            hardware.expectedClips=2;hardware.scheduleDurationMs=6000
            val scope=app.graph.session.capture()!!
            val items=listOf("a","b").map {id ->
                val uri=Uri.parse("soundq://track/7/$id");grants[uri.toString()]=MediaGrant(scope,TrackId(7))
                MediaItem.Builder().setMediaId(id).setUri(uri).setMediaMetadata(MediaMetadata.Builder().setExtras(Bundle().apply{putLong("trackId",7);putLong("durationMs",3000)}).build()).build()
            }
            player.setMediaItems(items,0,1250);player.prepare()
            app.graph.timeline.observe(scope,items.map{TimelineSource(it.mediaId,7,"Fixture",3000,QueueSegment.Context)})
            drain{player.playbackState==Player.STATE_READY&&field("account").get(service)!=null}
            projection=ControllerProjection(app,session.token)
            drain{projection.state.value.connection==PlaybackProjection.Connection.Connected&&projection.state.value.canAuditionArrangement}
            queue=QueueResumeEntrypoint(QueueResumeModel(app.graph,projection))
        }
        fun drain(predicate:()->Boolean) {
            val deadline=System.nanoTime()+TimeUnit.SECONDS.toNanos(5)
            while(true) {
                val owner=NativeCallbackPlayer::class.java.getDeclaredField("owner").apply{isAccessible=true}.get(player)
                val thread=owner.javaClass.getDeclaredField("thread").apply{isAccessible=true}.get(owner) as android.os.HandlerThread
                Shadows.shadowOf(thread.looper).idleFor(java.time.Duration.ofMillis(50));Shadows.shadowOf(Looper.getMainLooper()).idleFor(java.time.Duration.ofMillis(100))
                if(predicate())return
                check(System.nanoTime()<deadline){"Queue resume acknowledgement deadline: ${projectionOrNull()} native=${player.nativeDiagnostics()}"};Thread.sleep(5)
            }
        }
        private fun projectionOrNull()=runCatching{projection.state.value}.getOrNull()
        fun moveFirst() {
            val before=app.graph.timeline.state.value.document
            assertTrue(app.graph.timeline.commit(TimelineEdit(before.revision,before.clips[0],EditKind.Placement,500)){true})
            assertEquals(500L,app.graph.timeline.state.value.document.clips[0].globalStartMs)
        }
        fun installed()=field("acceptedArrangement").get(service) as? AcceptedArrangement
        override fun close() {
            projection.close();hardware.allowRetire=true;hardware.allowOrdinaryRetire=true;lifecycle.destroy()
            val deadline=System.nanoTime()+TimeUnit.SECONDS.toNanos(5)
            while(!player.nativeReleased.isDone&&System.nanoTime()<deadline){Shadows.shadowOf(Looper.getMainLooper()).idle();Thread.sleep(5)}
            assertTrue(player.nativeReleased.isDone);app.graph.close()
        }
    }
    @Test fun queueWaveformScrubAndMoveThenPlayResumesMappedCursorAfterNativeAck() {
        Fixture().use {f ->
            // Same production source-seek invoked by TimelinePanel's ruler release.
            f.queue.scrub(1750)
            f.drain{f.player.currentPosition==1750L&&f.projection.state.value.positionMs==1750L}
            f.moveFirst();f.hardware.ready=true
            f.queue.primaryAction()
            f.drain{f.installed()!=null&&f.player.isPlaying}
            assertEquals("Source 1750 + accepted placement 500 must not restart at zero",2250L,f.player.currentPosition)
            assertTrue(f.hardware.ops.contains(3));assertEquals(1,f.hardware.ops.count{it==4})
            val installed=f.installed()!!
            f.projection.pause();f.drain{!f.player.playWhenReady}
            f.queue.primaryAction();f.drain{f.player.isPlaying}
            assertEquals(2250L,f.player.currentPosition);assertSame(installed,f.installed())
            assertEquals("Unchanged paused resume must not reinstall",1,f.hardware.ops.count{it==4})
        }
    }
    @Test fun changedInstalledDocumentRetainsGlobalScrubRatherThanRestarting() {
        Fixture().use {f ->
            f.hardware.ready=true;f.queue.primaryAction();f.drain{f.installed()!=null&&f.player.isPlaying}
            val old=f.installed()!!
            f.queue.scrub(1900);f.drain{f.player.currentPosition==1900L&&!f.player.playWhenReady&&f.projection.state.value.positionMs==1900L}
            f.moveFirst();f.hardware.allowRetire=true
            f.queue.primaryAction();f.drain{f.installed()?.identity!=old.identity&&f.player.isPlaying}
            assertEquals("Installed arrangement cursor is already global",1900L,f.player.currentPosition)
            assertEquals(2,f.hardware.ops.count{it==4})
        }
    }
    @Test fun canceledQueueInstallCannotAutoplayAfterHeldSeekAckThenExplicitPlayStillWorks() {
        Fixture().use {f ->
            f.moveFirst();f.hardware.ready=true;f.hardware.holdSeekAck=true
            f.queue.primaryAction()
            f.drain{f.installed()!=null&&f.hardware.ops.contains(3)&&f.player.preparationSettled&&f.queue.auditionRequest==null}
            assertFalse("Native seek admission is not a cursor acknowledgement",f.player.isPlaying)
            assertFalse(f.hardware.ops.contains(1))
            // Actual compact-player cancel/pause entrypoint after install ACK.
            println("WAVEFORM_CANCEL before projection=${f.projection.state.value} intent=${f.player.playWhenReady} playing=${f.player.isPlaying} native=${f.player.nativeDiagnostics()} request=${f.queue.auditionRequest} pending=${f.field("pendingArrangement").get(f.service)}")
            f.queue.primaryAction()
            println("WAVEFORM_CANCEL after projection=${f.projection.state.value} intent=${f.player.playWhenReady} playing=${f.player.isPlaying} native=${f.player.nativeDiagnostics()} request=${f.queue.auditionRequest} pending=${f.field("pendingArrangement").get(f.service)}")
            f.drain{!f.player.playWhenReady}
            assertNull(f.field("pendingArrangement").get(f.service))
            f.hardware.holdSeekAck=false
            f.drain{f.player.currentPosition==1750L&&f.player.playbackState==Player.STATE_READY}
            assertFalse(f.player.isPlaying);assertFalse(f.hardware.ops.contains(1))
            f.queue.primaryAction();f.drain{f.player.isPlaying}
            assertEquals(1750L,f.player.currentPosition)
        }
    }
    @Test fun ordinaryPausedQueueResumeWithoutWaveformInstallRetainsSourceCursor() {
        Fixture().use {f ->
            f.queue.showTimeline=false;f.queue.primaryAction();f.drain{f.player.isPlaying}
            assertEquals(1250L,f.player.currentPosition);assertNull(f.installed());assertFalse(f.hardware.ops.contains(4))
            f.projection.pause();f.drain{!f.player.playWhenReady}
            f.queue.primaryAction();f.drain{f.player.isPlaying};assertEquals(1250L,f.player.currentPosition)
        }
    }
}
internal class QueueResumeApplication:SoundQApplication() {
    val hardware=NativeArrangementPlayerTest.Hardware()
    override fun onCreate() {
        graph=com.soundq.android.AppGraph(this,ApiEndpoint.parse("https://fixture.invalid/api/v1"),store=object:SessionStore {
            override fun load(endpoint:ApiEndpoint):SecretTokens?=null
            override fun save(endpoint:ApiEndpoint,tokens:SecretTokens){}
            override fun clear(){}
        })
        check(graph.session.accept(graph.session.beginIntent(),SecretTokens("fixture","fixture","fixture")))
    }
    override fun createCallbackLibraryPlayer(grants:ConcurrentHashMap<String,MediaGrant>,jobs:CoroutineScope):Player {
        val calls=object:NativeCallbackCalls by hardware {
            override fun control(handle:Long,operation:Int,deck:Int,value:Double,eventNanos:Long):Boolean {
                val accepted=hardware.control(handle,operation,deck,value,eventNanos)
                if(operation==3&&accepted)hardware.javaClass.getDeclaredField("position").apply{isAccessible=true}.setLong(hardware,value.toLong())
                return accepted
            }
        }
        return NativeCallbackPlayer(graph,grants,jobs,calls,NativeCallbackSource {item,current ->
            check(current());File(graph.directory,item.mediaId+".encoded").apply{writeBytes(byteArrayOf(1,2,3))}
        })
    }
}
