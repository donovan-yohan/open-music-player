#!/usr/bin/env python3
"""Verify frozen design bytes, regenerate only the canonical Compose adapter."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "design-input"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--import-output", action="store_true")
args = parser.parse_args()
manifest = json.loads((BUNDLE / "manifest.json").read_text())
for name, expected in manifest["files"].items():
    assert hashlib.sha256((BUNDLE / name).read_bytes()).hexdigest() == expected, name
spec = importlib.util.spec_from_file_location("soundq_exporter", BUNDLE / "scripts/build_tokens.py")
assert spec is not None and spec.loader is not None
exporter = importlib.util.module_from_spec(spec)
spec.loader.exec_module(exporter)
output = exporter.render(exporter.load_source(BUNDLE / "tokens/soundq.tokens.json"))["SoundQComposeTokens.kt"]
assert output == (BUNDLE / "generated/SoundQComposeTokens.kt").read_text(), "frozen source/output drift"
target = ROOT / "designsystem/src/generated/kotlin/soundq/design/generated/SoundQComposeTokens.kt"
if args.import_output:
    target.write_text(output)
assert target.read_text() == output, "native output drift; run --import-output"
fonts = {"SpaceGrotesk-Regular.ttf": "space_regular.ttf", "SpaceGrotesk-SemiBold.ttf": "space_semibold.ttf", "IBMPlexMono-Regular.ttf": "plex_regular.ttf"}
for source, target_name in fonts.items():
    source_path = next(BUNDLE.glob("assets/fonts/*/" + source))
    assert source_path.read_bytes() == (ROOT / "designsystem/src/main/res/font" / target_name).read_bytes(), source
assert (BUNDLE / "assets/brand/soundq-logo.png").read_bytes() == (ROOT / "app/src/main/res/drawable-nodpi/soundq_logo.png").read_bytes()
release = BUNDLE / "release"
release_manifest = json.loads((release / "MANIFEST.json").read_text())
for name, expected in release_manifest["files"].items():
    assert hashlib.sha256((release / name).read_bytes()).hexdigest() == expected, name
queue_release = BUNDLE / "queue-r1"
queue_manifest = json.loads((queue_release / "manifest.json").read_text())
assert queue_manifest["kind"] == "consumed-subset-not-full-release"
for name, expected in queue_manifest["files"].items():
    assert hashlib.sha256((queue_release / name).read_bytes()).hexdigest() == expected, name
assert (queue_release / "generated/SoundQIcons.kt").read_bytes() == (ROOT / "designsystem/src/generated/kotlin/soundq/design/generated/SoundQIcons.kt").read_bytes()
assert (queue_release / "tokens/soundq.tokens.json").read_bytes() == (BUNDLE / "tokens/soundq.tokens.json").read_bytes()
assert (queue_release / "scripts/build_tokens.py").read_bytes() == (BUNDLE / "scripts/build_tokens.py").read_bytes()
# W9 is additive. Resolve immutable base, shared roles, then Light only overlay.
import copy
appearance = BUNDLE / "appearance-w9"
provenance = json.loads((appearance / "provenance.json").read_text())
assert provenance["kind"] == "consumed-subset-not-full-release"
for name, expected in provenance["files"].items():
    assert hashlib.sha256((appearance / name).read_bytes()).hexdigest() == expected, name
assert (appearance / "canonical/tokens/soundq.tokens.json").read_bytes() == (BUNDLE / "tokens/soundq.tokens.json").read_bytes()
assert (appearance / "tools/build_tokens.py").read_bytes() == (BUNDLE / "scripts/build_tokens.py").read_bytes()
def merge(a, b):
    for key, value in b.items():
        if isinstance(value, dict) and "$value" not in value and isinstance(a.get(key), dict):
            merge(a[key], value)
        else:
            a[key] = copy.deepcopy(value)
    return a
resolved = {}
for mode in ("dark", "light"):
    document = merge(json.loads((appearance / "canonical/tokens/soundq.tokens.json").read_text()), json.loads((appearance / "tokens/shared.roles.json").read_text()))
    if mode == "light":
        merge(document, json.loads((appearance / "tokens/light.overlay.json").read_text()))
    resolved[mode] = exporter.resolve(document)
    output = exporter.render(document)["SoundQComposeTokens.kt"].replace("object SoundQComposeTokens {", "object SoundQ" + mode.title() + "Tokens {").replace("Generated from tokens/soundq.tokens.json", "Generated by W9 build.py: immutable canonical + shared.roles + optional light.overlay")
    assert output == (appearance / ("generated/" + mode + ".SoundQComposeTokens.kt")).read_text()
    target = ROOT / ("designsystem/src/generated/kotlin/soundq/design/generated/SoundQ" + mode.title() + "Tokens.kt")
    if args.import_output:
        target.write_text(output)
    assert target.read_text() == output, target
# Regenerate the typed role mapping using the released generator's actual body.
import ast
module = ast.parse((appearance / "build.py").read_text())
function = next(n for n in module.body if isinstance(n, ast.FunctionDef) and n.name == "run")
start = next(i for i, n in enumerate(function.body) if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "colorpaths" for t in n.targets))
end = next(i for i, n in enumerate(function.body) if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "inputs" for t in n.targets))
outputs = {}
scope = {"m": exporter, "resolved": {mode: {key: exporter.normalized(*value) for key, value in values.items()} for mode, values in resolved.items()}, "put": lambda name, value: outputs.update({name: value})}
exec(compile(ast.Module(body=function.body[start:end], type_ignores=[]), "released-w9-mapping", "exec"), scope)
output = outputs["generated/SoundQAppearanceMapping.kt"]
assert output == (appearance / "generated/SoundQAppearanceMapping.kt").read_text()
target = ROOT / "designsystem/src/generated/kotlin/soundq/design/generated/SoundQAppearanceMapping.kt"
if args.import_output:
    target.write_text(output)
assert target.read_text() == output
# W10 is independently sealed and additive; base and W9 checks above remain authoritative.
import subprocess
import sys
subprocess.run([sys.executable, "-B", str(ROOT / "scripts/check-spectral-design.py"), *(["--import-output"] if args.import_output else [])], check=True)
print(json.dumps({"status": "ok", "provisional": True, "input_files": len(manifest["files"]), "appearance_files": len(provenance["files"]), "tracking_unit": "TextUnit via canonical sp exporter"}))
