#!/usr/bin/env python3
"""Compile Queue callback plus real playback/service; isolated cached host JVM only."""
import argparse
import os
from pathlib import Path
import subprocess

p=argparse.ArgumentParser()
p.add_argument('--build',type=Path,required=True)
p.add_argument('--source-root',type=Path)
p.add_argument('--app-classes',type=Path,help='Read-only exact parent build Kotlin classes; otherwise compile non-UI production from source')
a=p.parse_args()
root=Path(__file__).resolve().parents[1]
source=a.source_root or root
a.build.mkdir(parents=True,exist_ok=True)
queue=(source/'app/src/main/kotlin/com/soundq/android/product/QueuePanel.kt').read_text()
start=queue.index('    fun primaryAction()');opening=queue.index('{',start);end=opening+1;depth=1
while depth:
    depth+=(queue[end]=='{')-(queue[end]=='}');end+=1
body=queue[start:end]
timeline=(source/'app/src/main/kotlin/com/soundq/android/product/timeline/StackedTimeline.kt').read_text()
scrub_start=timeline.index('onScrub={ms ->')+len('onScrub={ms ->')
scrub_end=scrub_start;depth=1
while depth:
    depth+=(timeline[scrub_end]=='{')-(timeline[scrub_end]=='}');scrub_end+=1
scrub=timeline[scrub_start:scrub_end-1]
caller=a.build/'QueueResumeEntrypoint.kt'
caller.write_text('''package com.soundq.android.playback.nativeengine
import com.soundq.android.AppGraph
import com.soundq.android.playback.*
import com.soundq.android.data.timeline.*
internal class QueueResumeModel(val graph:AppGraph,val controller:ControllerProjection) {val timeline=graph.timeline.state;val playback=controller.state}
internal class QueueResumeEntrypoint(val model:QueueResumeModel) {
 val playback get()=model.controller.state.value
 var showTimeline=true
 val scope=model.graph.session.capture()
 var live=true
 val valid:()->Boolean={live}
 val timelineAdmission=java.util.concurrent.atomic.AtomicReference<()->Boolean>({live})
 var auditionRequest:String?=null
 var auditionMessage:String?=null
'''+body+'\n fun scrub(ms:Long) {val document=model.timeline.value.document;val admitted:()->Boolean=valid;'+scrub+'}\n}\n')
# Reuse the established pinned compiler/classpath discovery, but keep all emitted
# classes, reports and facade extraction local to --build. Do not edit shared runner.
runner=(root/'scripts/test-overlap-compile.py').read_text()
runner=runner.replace("r=Path(__file__).resolve().parents[2]",'r=Path('+repr(str(root.parent))+')')
runner=runner.replace("sources=list((base/'nativeengine').glob('*.kt'))", "sources=list((base/'nativeengine').glob('*.kt'))")
if a.app_classes:
    runner=runner.replace("r/'android/app/build/intermediates/built_in_kotlinc/debug/compileDebugKotlin/classes'",'Path('+repr(str(a.app_classes))+')')
else:
    # Build only non-visual production source. BuildConfig is generated by AGP;
    # this host-only declaration uses an unroutable fixture endpoint.
    config=a.build/'BuildConfig.kt'
    config.write_text('package com.soundq.android\nclass MainActivity:android.app.Activity()\nobject BuildConfig {const val OMP_API_BASE_URL="https://fixture.invalid/api/v1";const val OMP_BUILD_ID="fixture";const val OMP_SOURCE_REF="fixture"}\n')
    runner=runner.replace("sources.append(base.parent/'data/timeline/TimelineRepository.kt')", "sources=list(base.rglob('*.kt'))+list((base.parent/'data').rglob('*.kt'))+list((base.parent/'localunlock').rglob('*.kt'))+[base.parent/'SoundQApplication.kt']+[x for x in (base.parent/'product/artwork').glob('*.kt') if '@Composable' not in x.read_text()]+[Path("+repr(str(config))+")]\ncp=cp[1:]")
if a.source_root:
    # Overlay only owned changed playback files; all other collaborators remain
    # current production. This also works for the source-only compilation route.
    mapping="sources=[Path(str(x).replace(str(r/'android'),"+repr(str(source))+")) if x.name in ('ControllerProjection.kt','SoundQLibraryService.kt','NativeCallbackPlayer.kt') else x for x in sources]"
    runner=runner.replace('if a.player_tests:',mapping+'\nif a.player_tests:',1)
runner=runner.replace("sources.extend([r/'android/scripts/NativeArrangementPlayerTest.kt',r/'android/scripts/NativeOverlapServiceApplication.kt'])", "sources.extend([r/'android/scripts/NativeArrangementPlayerTest.kt',r/'android/scripts/NativeOverlapServiceApplication.kt',r/'android/scripts/NativeQueueWaveformResumeTest.kt',Path("+repr(str(caller))+")])")
runner=runner.replace("'com.soundq.android.playback.nativeengine.NativeArrangementPlayerTest'", "'com.soundq.android.playback.nativeengine.NativeQueueWaveformResumeTest','com.soundq.android.playback.nativeengine.NativeArrangementPlayerTest'")
script=a.build/'compile.py';script.write_text(runner)
subprocess.run(['python3',str(script),'--build',str(a.build/'compiled'),'--player-tests'],check=True,env=dict(os.environ,TMPDIR=str(a.build)))
